/**
 * Tool 4 — dispatch_care_circle_digest → ui://echocare/care-circle
 * AWS Bedrock Runtime + Strands-style multi-agent Family Care Circle digest.
 */
import { z } from "zod";
import {
  runCareCircleDigestPipeline,
  type DayTelemetry,
} from "../../agent/aws-bedrock-strands.js";
import { CARE_CIRCLE, ELDER } from "../../data/elder-profile.js";
import { adherencePct, dayState } from "../state.js";

export const careCircleInputSchema = {
  action: z
    .enum(["compose", "send", "export"])
    .default("compose")
    .describe("compose = run the Bedrock/Strands pipeline; send = deliver to the care circle; export = clinical summary for the physician"),
};

export interface CareCircleArgs {
  action?: "compose" | "send" | "export";
}

function buildTelemetry(): DayTelemetry {
  const biomarkers = dayState.lastBiomarkers;
  const drift = dayState.lastDrift;
  return {
    elderName: ELDER.name,
    dateLabel: "Saturday 18 October 2026",
    cognitiveComposite: biomarkers?.compositeScore ?? 84,
    cognitiveBaselineMean: drift?.baselineCompositeMean ?? 84,
    cognitiveDriftLevel: drift?.alertLevel ?? "steady",
    mattr: biomarkers?.mattr ?? 0.72,
    orientationIndex: biomarkers?.orientation.index ?? 92,
    medicationAdherencePct: adherencePct(),
    dosesConfirmed: dayState.dosesConfirmed,
    dosesScheduled: dayState.dosesScheduled,
    preventedInteractions: dayState.preventedInteractions.map((p) => ({
      drug: p.drug,
      interactsWith: p.interactsWith,
      severity: p.severity,
    })),
    resolvedAnomalies: [...dayState.resolvedAnomalies],
    openAnomalies: dayState.openIncidentIds.size,
    hydrationGlasses: dayState.hydrationGlasses,
    hydrationGoal: dayState.hydrationGoal,
    sleepHours: dayState.sleepHours,
    stepsEstimate: dayState.stepsEstimate,
  };
}

function clinicalSummary(telemetry: DayTelemetry): string {
  return [
    `ECHOCARE KINSHIP — CLINICAL HANDOFF SUMMARY (wellness screening, non-diagnostic)`,
    `Patient: ${ELDER.name}, ${ELDER.age} · ${ELDER.livingSituation}`,
    `Date: ${telemetry.dateLabel}`,
    ``,
    `COGNITIVE SCREEN (speech biomarkers vs 7-day personal baseline)`,
    `  Composite ${telemetry.cognitiveComposite}/100 vs baseline ${telemetry.cognitiveBaselineMean} · drift=${telemetry.cognitiveDriftLevel}`,
    `  MATTR ${telemetry.mattr} · Orientation index ${telemetry.orientationIndex}/100`,
    ``,
    `MEDICATION`,
    `  Adherence ${telemetry.medicationAdherencePct}% (${telemetry.dosesConfirmed}/${telemetry.dosesScheduled})`,
    ...dayState.doseLog.map((d) => `  · ${d.at} — ${d.note}`),
    ...(telemetry.preventedInteractions.length
      ? telemetry.preventedInteractions.map(
          (p) => `  PREVENTED ADE: ${p.drug} + ${p.interactsWith} (${p.severity}) blocked pre-confirmation`,
        )
      : [`  No intercepted interactions today.`]),
    ``,
    `HOME SAFETY`,
    ...(telemetry.resolvedAnomalies.length
      ? telemetry.resolvedAnomalies.map((a) => `  Resolved: ${a.scenario} → ${a.resolution}`)
      : [`  No anomalies required intervention.`]),
    `  Open incidents: ${telemetry.openAnomalies}`,
    ``,
    `VITALS-ADJACENT (ambient estimates)`,
    `  Hydration ${telemetry.hydrationGlasses}/${telemetry.hydrationGoal} glasses · Sleep ${telemetry.sleepHours} h · Steps ≈ ${telemetry.stepsEstimate}`,
    ``,
    `Generated by EchoCare Kinship (AWS Bedrock + Strands-style agents). Screening signals only.`,
  ].join("\n");
}

export async function runCareCircleDigest(args: CareCircleArgs = {}) {
  const action = args.action ?? "compose";
  const telemetry = buildTelemetry();

  const digest =
    action === "compose" || !dayState.lastDigest
      ? await runCareCircleDigestPipeline(telemetry)
      : dayState.lastDigest;
  dayState.lastDigest = digest;

  let statusLine = `Digest composed by ${digest.trace.length} Strands agents (${digest.mode}). Not yet sent.`;
  let clinicalExport: string | undefined;

  if (action === "send") {
    dayState.digestSentTo = CARE_CIRCLE.filter((p) => p.id !== "pharm").map((p) => p.id);
    statusLine = `📤 Delivered at ${new Date().toISOString()} → Tolu (Alexa app + SMS), Kunle (Alexa app), Dr. Okafor (clinical copy). Read receipts will appear here.`;
  }
  if (action === "export") {
    clinicalExport = clinicalSummary(telemetry);
    statusLine = "🧾 Clinical summary generated for Dr. Okafor (plain-text export, FHIR-ready structure).";
  }

  const alexaSays =
    action === "send"
      ? `I've sent today's family digest, Mama Adebayo. Tolu, Kunle and Dr. Okafor will see that you're doing well — peace-of-mind score ${digest.peaceOfMindScore} out of 100.`
      : action === "export"
        ? "Your clinical summary is ready for Dr. Okafor, Mama Adebayo — biomarkers, medicines and today's safety notes, all in one page."
        : `Here's today's family digest preview, Mama Adebayo — composed by our AWS Bedrock agents. Overall peace-of-mind is ${digest.peaceOfMindScore} out of 100: ${digest.peaceOfMindBand}. Shall I send it to Tolu and Kunle?`;

  return {
    text: `Care Circle digest (${digest.mode}): Peace-of-Mind ${digest.peaceOfMindScore}/100 (${digest.peaceOfMindBand}). ${digest.headline}`,
    structuredContent: {
      view: "ui://echocare/care-circle",
      digest,
      telemetry,
      careCircle: CARE_CIRCLE.map((p) => ({ ...p })),
      sentTo: [...dayState.digestSentTo],
      clinicalExport,
      statusLine,
      alexaSays,
      disclaimer: "Family wellness digest — screening signals, not a medical diagnosis.",
    },
  };
}
